/**
 * Strip deck info from a player after game start.
 * Mirrors: (strip-deck player)
 */
function stripDeck(player: Record<string, unknown>): Record<string, unknown> {
  const deck = player.deck as Record<string, unknown> | undefined;
  if (!deck) return player;

  const strippedDeck: Record<string, unknown> = {
    _id: String((deck._id as any) ?? ""),
    identity: (deck.identity as Record<string, unknown>) || {},
    name: deck.name,
  };
  // Keep only title and faction from identity
  const identity = strippedDeck.identity as Record<string, unknown>;
  strippedDeck.identity = {
    title: identity.title,
    faction: identity.faction,
  };

  return { ...player, deck: strippedDeck };
}

/**
 * Map a deck onto a player in the players list.
 * Mirrors: (player-map-deck players uid deck)
 */
function playerMapDeck(
  players: Record<string, unknown>[],
  uid: string,
  deck: Record<string, unknown>,
): Record<string, unknown>[] {
  return players.map((p) =>
    (p as any).uid === uid ? { ...p, deck } : p,
  );
}

/**
 * Get the uid of the player on the given side.
 * Mirrors: (side-player-uid game side)
 */
function sidePlayerUid(game: Lobby, side: string): string | undefined {
  const player = (game.players ?? []).find(
    (p) => (p as any).side === side,
  ) as Record<string, unknown> | undefined;
  return player ? (player as any).uid : undefined;
}

/**
 * Set preconstructed deck for one side.
 * Mirrors: (set-precon-deck game side decklist)
 */
function setPreconDeck(
  game: Lobby,
  side: string,
  decklist: Record<string, unknown>,
): Lobby {
  const uid = sidePlayerUid(game, side);
  if (!uid) return game;

  const deck = processDeck(decklist as any);
  return {
    ...game,
    players: playerMapDeck(game.players ?? [], uid, deck),
  };
}

/**
 * Set preconstructed decks for both sides.
 * Mirrors: (set-precon-match game precon-match)
 */
function setPreconMatch(
  game: Lobby,
  preconMatch: { corp: Record<string, unknown>; runner: Record<string, unknown> },
): Lobby {
  let result = setPreconDeck(game, "Corp", preconMatch.corp);
  result = setPreconDeck(result, "Runner", preconMatch.runner);
  return result;
}

/**
 * Handle preconstructed / chimera deck setup.
 * Mirrors: (handle-precon-decks game)
 */
function handlePreconDecks(game: Lobby): Lobby {
  const precon = (game as any).precon as string | undefined;
  if (precon) {
    const matchup = matchupByKey(precon as any);
    if (matchup) {
      return setPreconMatch(game, {
        corp: matchup.corp as unknown as Record<string, unknown>,
        runner: matchup.runner as unknown as Record<string, unknown>,
      });
    }
  }

  const format = (game as any).format as string | undefined;
  if (format === "chimera") {
    const corpDeck = makeCorpDeck();
    const runnerDeck = makeRunnerDeck();
    return setPreconMatch(game, {
      corp: corpDeck as unknown as Record<string, unknown>,
      runner: runnerDeck as unknown as Record<string, unknown>,
    });
  }

  return game;
}

