/**
 * Handle starting a game.
 * Mirrors: (handle-start-game lobbies gameid players now)
 */
function handleStartGame(
  lobbies: Record<string, Lobby>,
  gameid: string,
  players: Record<string, unknown>[],
  now: Date,
): Record<string, Lobby> {
  const lobby = lobbies[gameid];
  if (!lobby) return lobbies;

  // handle-precon-decks
  let game = handlePreconDecks(lobby);

  // merge started, original-players, ending-players, start-date, last-update, state
  game = {
    ...game,
    started: true,
    "original-players": players,
    "ending-players": players,
    "start-date": now,
    "last-update": now,
    // init-game – create the game state from the lobby config.
    // In the full port, this calls game.core.set-up/init-game.
    // For now, delegate to whatever state initialization the lobby already carries.
    state: (game as any).state ?? {},
  };

  // check-for-starter-decks
  game = checkForStarterDecks(game);

  // strip decks
  game = {
    ...game,
    players: (game.players ?? []).map((p: Record<string, unknown>) => stripDeck(p)),
  };

  return { ...lobbies, [gameid]: game };
}

/**
 * Attempt to start a game (first player only).
 * Mirrors: (try-start-game db uid gameid)
 */
export function tryStartGame(db: Db, uid: string, gameid: string): void {
  const lobby = getLobby(gameid);
  if (!lobby) return;

  const first = firstPlayerInLobby(uid, lobby);
  if (!first || lobby.started) return;

  const now = new Date();
  const newAppState = swapAppState((state) => ({
    ...state,
    lobbies: handleStartGame(state.lobbies, gameid, lobby.players ?? [], now),
  }));

  const lobbyExists = newAppState.lobbies[gameid];
  if (lobbyExists) {
    gameStarted(db, lobbyExists as any);
    sendLobbyState(lobbyExists);
    broadcastLobbyList();
    const state = (lobbyExists as any).state;
    if (state) {
      sendStateToParticipants("game/start", lobbyExists, publicStates(state as any));
    }
  }
}

