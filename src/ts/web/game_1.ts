/** :game/start */
registerMsgHandler("game/start", (msg: WSMessage) => {
  const uid = msg.uid as string;
  const ringReq = (msg as any).ringReq ?? {};
  const db = ringReq.system?.db as Db | undefined;
  const data = msg.data as Record<string, unknown> | undefined;
  const gameid = data?.gameid as string | undefined;
  const timestamp = msg.timestamp ?? Date.now();
  const id = msg.id ?? "game/start";

  lobbyThread(() => {
    const appState = getAppState();
    if (appState["block-game-creation"]) {
      chskSend(uid, [
        "lobby/toast",
        { message: "lobby_creation-paused", type: "error" },
      ]);
    } else if (db && gameid) {
      tryStartGame(db, uid, gameid);
    }
  });
  logDelay(timestamp, id);
});

/** :game/leave */
registerMsgHandler("game/leave", (msg: WSMessage) => {
  const uid = msg.uid as string;
  const ringReq = (msg as any).ringReq ?? {};
  const db = ringReq.system?.db as Db | undefined;
  const user = ringReq.user ?? {};
  const data = msg.data as Record<string, unknown> | undefined;
  const gameid = data?.gameid as string | undefined;
  const replyFn = (msg as any).replyFn;
  const timestamp = msg.timestamp ?? Date.now();
  const id = msg.id ?? "game/leave";

  lobbyThread(() => {
    const lobby = getLobby(gameid as string);
    if (!lobby || !inLobby(uid, lobby) || !lobby.started || !(lobby as any).state) return;

    // The game will not exist if this is the last player to leave.
    if (!db) return;
    const lobbyAfter = leaveLobby(db, user, uid, replyFn, lobby);
    if (lobbyAfter) {
      handleMessageAndSendDiffs(
        lobbyAfter,
        null,
        null,
        `${(user as any).username ?? "User"} has left the game.`,
      );
    }
    sendLobbyList(uid);
    broadcastLobbyList();
  });
  logDelay(timestamp, id);
});
