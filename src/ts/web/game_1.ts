/**
 * Check if a player is using a starter deck.
 * Mirrors: (is-starter-deck? player)
 */
function isStarterDeck(player: Record<string, unknown>): boolean {
  const deck = player.deck as Record<string, unknown> | undefined;
  if (!deck) return false;
  const identity = (deck.identity as Record<string, unknown>) || {};
  const id = identity.title as string | undefined;
  const cards = (deck.cards as Array<{ qty: number }> | undefined) ?? [];
  const cardCnt = cards.reduce((sum, c) => sum + (c.qty ?? 0), 0);

  return (
    (id === "The Syndicate: Profit over Principle" && cardCnt === 34) ||
    (id === "The Catalyst: Convention Breaker" && cardCnt === 30)
  );
}

/**
 * Starter Decks can require 6 or 7 agenda points.
 * Mirrors: (check-for-starter-decks game)
 */
function checkForStarterDecks(game: Lobby): Lobby {
  const format = (game as any).format as string | undefined;
  const players = game.players ?? [];

  if (format === "system-gateway" && players.every(isStarterDeck)) {
    const state = (game as any).state as Record<string, unknown> | undefined;
    if (state) {
      const runner = (state.runner as Record<string, unknown>) || {};
      const corp = (state.corp as Record<string, unknown>) || {};
      runner["agenda-point-req"] = 6;
      corp["agenda-point-req"] = 6;
      state.runner = runner;
      state.corp = corp;
    }
  }
  return game;
}

