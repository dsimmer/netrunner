/**
 * Converts the appropriate diff to JSON for the given user.
 * Mirrors: (game-diff-json uid gameid side corp-spectators runner-spectators diffs)
 */
function gameDiffJson(
  uid: string,
  gameid: string,
  side: string,
  corpSpectators: Record<string, unknown>[],
  runnerSpectators: Record<string, unknown>[],
  diffs: PublicDiffs | MessageDiffs,
): string {
  const diff =
    side === "Corp"
      ? (diffs as PublicDiffs)["corp-diff"]
      : side === "Runner"
        ? (diffs as PublicDiffs)["runner-diff"]
        : corpSpectators.some((p) => (p as any).uid === uid)
          ? (diffs as PublicDiffs)["corp-spect-diff"]
          : runnerSpectators.some((p) => (p as any).uid === uid)
            ? (diffs as PublicDiffs)["runner-spect-diff"]
            : (diffs as PublicDiffs | MessageDiffs)["spect-diff"];

  return JSON.stringify({ gameid, diff });
}

/**
 * Sends diffs generated by public-diffs to all connected clients.
 * Mirrors: (send-state-diffs lobby diffs)
 */
export function sendStateDiffs(
  lobby: Lobby,
  diffs: PublicDiffs | MessageDiffs,
): void {
  const allUsers = [
    ...(lobby.players ?? []),
    ...(lobby.spectators ?? []),
  ];
  const corpSpectators = (lobby["corp-spectators"] ?? []) as Record<string, unknown>[];
  const runnerSpectators = (lobby["runner-spectators"] ?? []) as Record<string, unknown>[];

  for (const user of allUsers) {
    const uid = (user as any).uid as string | undefined;
    if (!uid) continue;
    const side = (user as any).side as string | undefined;
    chskSend(uid, [
      "game/diff",
      gameDiffJson(uid, String(lobby.gameid), side ?? "", corpSpectators, runnerSpectators, diffs),
    ]);
  }
}

