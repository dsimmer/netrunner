/**
 * Updates the old-states atom with the new game state, then sends a :game/diff
 * message to game clients.
 * Mirrors: (update-and-send-diffs! f lobby & args)
 */
export function updateAndSendDiffs<T extends any[]>(

  f: (state: Record<string, unknown>, ...args: T) => void,
  lobby: Lobby,
  ...args: T
): void {
  const state = (lobby as any).state as Record<string, unknown> | undefined;
  if (!state) return;

  const oldState = { ...state };
  f(state, ...args);

  const spectators = (lobby.spectators ?? []).length > 0;
  const corpSpectators = (lobby["corp-spectators"] ?? []).length > 0;
  const runnerSpectators = (lobby["runner-spectators"] ?? []).length > 0;

  const diffs = publicDiffs(oldState, state as any, spectators, corpSpectators, runnerSpectators);

  // Append hist-diff to history
  if (!state.history) (state as any).history = [];
  (state as any).history.push(diffs["hist-diff"]);

  sendStateDiffs(lobby, diffs);
}

