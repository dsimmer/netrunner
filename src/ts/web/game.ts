/**
 * If the given message is a command, passes through to `updateAndSendDiffs`.
 * Otherwise, adds the message to the log and only diffs the `:log`.
 * Mirrors: (handle-message-and-send-diffs! lobby side user message)
 */
export function handleMessageAndSendDiffs(
  lobby: Lobby,
  side: string | null,
  user: Record<string, unknown> | null,
  message: string,
): void {
  const state = (lobby as any).state as Record<string, unknown> | undefined;
  if (!state) return;

  // Mirror Clojure: (if (= (str/trim message) "null") " null" message)
  const normalizedMessage = message.trim() === "null" ? " null" : message;

  if (side && user && parseCommand(state as any, side, normalizedMessage)) {
    // It's a command – go through full state update + diffs
    updateAndSendDiffs(
      main.handleSay as any,
      lobby,
      side as any,
      user as any,
      normalizedMessage,
    );
  } else {
    // Notification / chat message – only log diff
    const f = side
      ? (main.handleSay as any)
      : (main.handleNotification as any);
    const oldState = { ...state };
    f(state as any, side ?? null, user ?? null, normalizedMessage);
    const diffs = messageDiffs(oldState, state as any);

    if (!state.history) (state as any).history = [];
    (state as any).history.push(diffs["hist-diff"]);
    sendStateDiffs(lobby, diffs);
  }
}

