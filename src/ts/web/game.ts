interface PublicStatesResult {
  "corp-state": Record<string, unknown>;
  "runner-state": Record<string, unknown>;
  "spect-state"?: Record<string, unknown>;
  "corp-spect-state"?: Record<string, unknown>;
  "runner-spect-state"?: Record<string, unknown>;
  "hist-state": Record<string, unknown>;
}

/**
 * Select the correct state view for a uid + side.
 * Mirrors: (select-state uid lobby side diffs)
 */
function selectState(
  uid: string,
  lobby: Lobby,
  side: string | undefined,
  diffs: PublicStatesResult,
): string {
  const corpSpectators = (lobby["corp-spectators"] ?? []) as Record<string, unknown>[];
  const runnerSpectators = (lobby["runner-spectators"] ?? []) as Record<string, unknown>[];

  let selected: Record<string, unknown>;
  if (side === "Corp") {
    selected = diffs["corp-state"];
  } else if (side === "Runner") {
    selected = diffs["runner-state"];
  } else if (corpSpectators.some((p) => (p as any).uid === uid)) {
    selected = diffs["corp-spect-state"];
  } else if (runnerSpectators.some((p) => (p as any).uid === uid)) {
    selected = diffs["runner-spect-state"];
  } else {
    selected = diffs["spect-state"];
  }

  return JSON.stringify(selected);
}

/**
 * Sends full states generated by public-states to all connected clients in lobby.
 * Mirrors: (send-state-to-participants event lobby diffs)
 */
function sendStateToParticipants(
  event: string,
  lobby: Lobby,
  diffs: PublicStatesResult,
): void {
  const allUsers = [
    ...(lobby.players ?? []),
    ...(lobby.spectators ?? []),
  ];
  for (const user of allUsers) {
    const uid = (user as any).uid as string | undefined;
    if (!uid) continue;
    const side = (user as any).side as string | undefined;
    chskSend(uid, [event, selectState(uid, lobby, side, diffs)]);
  }
}

/**
 * Sends full states generated by public-states to single client in lobby.
 * Mirrors: (send-state-to-uid! uid event lobby diffs)
 */
function sendStateToUid(
  uid: string,
  event: string,
  lobby: Lobby,
  diffs: PublicStatesResult,
): void {
  const allUsers = [
    ...(lobby.players ?? []),
    ...(lobby.spectators ?? []),
  ];
  const player = allUsers.find((p) => (p as any).uid === uid);
  if (!player) return;
  const side = (player as any).side as string | undefined;
  chskSend(uid, [event, selectState(uid, lobby, side, diffs)]);
}

